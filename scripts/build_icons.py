"""Bundle an icon for each app in the catalog, so the web app never fetches one from the app.

The web app used to load ``https://<app>.<domain>/favicon.ico`` for every app it listed.
The browser sends the domain-wide sign-on cookie with that request, so every app saw the
admin's session whenever Home was opened. Bundled icons are served by the daemon from its
own origin instead, and the page loads no image from anywhere else.

Icons come from homarr-labs/dashboard-icons (Apache-2.0), pinned to one commit. Each one is
downloaded, opened and re-encoded with Pillow as a small WebP, so only a clean raster image
ships: never an SVG (which can carry script), never a file as it was downloaded. Apps with no
icon there (mostly background tools without a web page) keep the coloured monogram.

Usage (maintainer tool, not run by CI or the release; the output is committed):

    uv run --no-project --with pillow python scripts/build_icons.py

Writes ``web/public/icons/<role>.webp``, ``web/public/icons/LICENSE`` and the generated
``web/src/lib/app-icons.ts`` that lists the roles that have an icon.
"""

from __future__ import annotations

import io
import json
import re
import sys
import urllib.request
from pathlib import Path

from PIL import Image

SOURCE = "homarr-labs/dashboard-icons"
COMMIT = "d4b500dc40a8e1043b1581cabb7208892cf35472"
RAW = f"https://raw.githubusercontent.com/{SOURCE}/{COMMIT}"
SIZE = 128  # px: sharp at the largest avatar (48 px) on a 2x screen
MAX_DOWNLOAD = 4 * 1024 * 1024

# The same product under another name. Only exact matches: a wrong logo is worse than none.
ALIASES = {
    "delugevpn": "deluge",
    "fireflyiii_importer": "firefly-iii",
    "influxdb2": "influxdb",
    "minecraft_bedrock": "minecraft",
    "mylar3": "mylar",
    "postgres_host": "postgres",
    "qbittorrentvpn": "qbittorrent",
    "semaphoreui": "semaphore",
    "tdarr_node": "tdarr",
    "transmissionvpn": "transmission",
    "unifi_network_application": "unifi",
}
ROLE = re.compile(r"[a-z0-9_]{1,64}")

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "saltbox_ui" / "catalog" / "data" / "apps.json"
OUT = ROOT / "web" / "public" / "icons"
MANIFEST = ROOT / "web" / "src" / "lib" / "app-icons.ts"


def get(path: str) -> bytes:
    # RAW is a fixed https address at a pinned commit; ``path`` comes from this script.
    with urllib.request.urlopen(f"{RAW}/{path}", timeout=30) as response:
        data = response.read(MAX_DOWNLOAD + 1)
    if len(data) > MAX_DOWNLOAD:
        raise ValueError(f"{path} is larger than {MAX_DOWNLOAD} bytes")
    return data


def candidates(role: str, title: str) -> list[str]:
    plain = title.lower()
    names = [
        ALIASES.get(role, ""),
        role,
        role.replace("_", "-"),
        re.sub(r"[^a-z0-9]+", "-", plain).strip("-"),
        re.sub(r"[^a-z0-9]+", "", plain),
    ]
    return [name for name in dict.fromkeys(names) if name]


def reencode(data: bytes) -> bytes:
    with Image.open(io.BytesIO(data)) as image:
        image.load()
        icon = image.convert("RGBA")
    icon.thumbnail((SIZE, SIZE), Image.Resampling.LANCZOS)
    out = io.BytesIO()
    icon.save(out, "WEBP", quality=88, method=6)
    return out.getvalue()


def main() -> int:
    available = {name.rsplit(".", 1)[0] for name in json.loads(get("tree.json"))["webp"]}
    entries = [app for apps in json.loads(CATALOG.read_text()).values() for app in apps]
    roles = sorted({(app["role"], app["title"]) for app in entries})

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.webp"):
        old.unlink()
    made: list[str] = []
    for role, title in roles:
        if not ROLE.fullmatch(role):
            raise ValueError(f"unexpected role name {role!r}")
        name = next((n for n in candidates(role, title) if n in available), None)
        if name is None:
            continue
        (OUT / f"{role}.webp").write_bytes(reencode(get(f"webp/{name}.webp")))
        made.append(role)
    (OUT / "LICENSE").write_bytes(get("LICENSE"))

    lines = [
        f"// Generated by scripts/build_icons.py from {SOURCE} at {COMMIT[:12]} (Apache-2.0).",
        "// Do not edit by hand. The roles whose icon is bundled in web/public/icons.",
        "export const APP_ICONS: ReadonlySet<string> = new Set([",
        *(f"  '{role}'," for role in made),
        "]);",
        "",
    ]
    MANIFEST.write_text("\n".join(lines))
    size = sum(path.stat().st_size for path in OUT.glob("*.webp"))
    print(f"{len(made)} of {len(roles)} apps have an icon ({size // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
